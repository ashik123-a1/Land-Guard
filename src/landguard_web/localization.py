def get_text(key: str, lang: str = "bn", **kwargs) -> str:
    """Translates key to target language with guaranteed safe fallback to English or original string.
    Supports case-insensitivity and space/underscore variations for enum statuses.
    Never returns None or empty string.
    """
    if not key:
        return ""
    str_key = str(key).strip()
    target_lang = lang if lang in TRANSLATIONS else "bn"

    def _lookup(k: str, l: str) -> Optional[str]:
        d = TRANSLATIONS.get(l, {})
        if k in d:
            return d[k]
        if k.upper() in d:
            return d[k.upper()]
        if "_" in k:
            spaced = k.replace("_", " ")
            if spaced in d:
                return d[spaced]
            if spaced.upper() in d:
                return d[spaced.upper()]
        if " " in k:
            underscored = k.replace(" ", "_")
            if underscored in d:
                return d[underscored]
            if underscored.upper() in d:
                return d[underscored.upper()]
        return None

    # 1. Lookup in target language
    trans = _lookup(str_key, target_lang)
    if trans is not None:
        if kwargs:
            try:
                return trans.format(**kwargs)
            except Exception:
                return trans
        return trans

    # 2. Fallback to English
    en_trans = _lookup(str_key, "en")
    if en_trans is not None:
        if kwargs:
            try:
                return en_trans.format(**kwargs)
            except Exception:
                return en_trans
        return en_trans

    # 3. Clean fallback to original string
    return str_key


translate = get_text


def get_preferred_language(request: Optional[Request] = None, user: Optional[Dict[str, Any]] = None) -> str:
    """Resolves language preference with hierarchy:
    1. Query parameter ?lang= (explicit override)
    2. HTTP Cookie 'landguard_lang'
    3. User profile 'preferred_language' from SQLite
    4. Default 'bn'
    """
    if request:
        try:
            if hasattr(request, "query_params"):
                q_lang = request.query_params.get("lang")
                if q_lang in ["en", "bn"]:
                    return q_lang
        except Exception:
            pass

        try:
            if hasattr(request, "cookies"):
                c_lang = request.cookies.get("landguard_lang")
                if c_lang in ["en", "bn"]:
                    return c_lang
        except Exception:
            pass

    if user and isinstance(user, dict):
        u_lang = user.get("preferred_language")
        if u_lang in ["en", "bn"]:
            return u_lang

    return "bn"
